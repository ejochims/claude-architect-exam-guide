// Builds option families: a holdout question and a practice twin that share all four options but key different ones.
// Usage: node scripts/audit/build-families.mjs <dir-of-family-json>
// Each JSON file: [{ f, ts, scenario, options: [t, t, t, t],
//   h: { id, stem, key, why: [w, w, w, w] }, p: { id, stem, key, why: [w, w, w, w] } }]
// Holdout members replace the holdout question with the same id; practice twins (b9-*) are rewritten at the end of bank.js.
// Re-running with more files is safe: earlier output is replaced, not duplicated.
import fs from "fs";
import path from "path";
import { ROOT, loadContent } from "./lib.mjs";

const dir = process.argv[2];
const fams = fs.readdirSync(dir).filter(f => f.endsWith(".json")).sort().flatMap(f => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));

const member = (fam, m, holdout) => {
  if (fam.options.length !== 4 || m.why.length !== 4 || !(m.key >= 0 && m.key < 4)) throw new Error(`${m.id}: need 4 options, 4 explanations, a key 0–3`);
  return { id: m.id, ts: fam.ts, scenario: fam.scenario, family: fam.f, holdout, stem: m.stem, options: fam.options.map((t, i) => ({ t, ...(i === m.key ? { ok: true } : {}), why: m.why[i] })) };
};
const opt = o => `      { t: ${JSON.stringify(o.t)}${o.ok ? ", ok: true" : ""}${o.trap ? `, trap: ${JSON.stringify(o.trap)}` : ""}, why: ${JSON.stringify(o.why)} }`;
const item = q => `  {\n    id: ${JSON.stringify(q.id)}, ts: ${JSON.stringify(q.ts)}, scenario: ${q.scenario},${q.holdout ? " holdout: true," : ""}${q.family ? ` family: ${JSON.stringify(q.family)},` : ""}\n    stem: ${JSON.stringify(q.stem)},\n    options: [\n${q.options.map(opt).join(",\n")}\n    ]\n  }`;

// Holdout: keep every existing question in order, swapping in the family version where one exists.
const byId = Object.fromEntries(fams.map(f => [f.h.id, member(f, f.h, true)]));
const holdout = loadContent().questions.filter(q => q.holdout).map(q => byId[q.id] || q);
const missing = Object.keys(byId).filter(id => !holdout.some(q => q.id === id));
if (missing.length) throw new Error(`holdout ids not found: ${missing.join(", ")}`);
const head = "// Sequestered Readiness Check items: never shown in lessons, drills or mocks. Take the check once, cold.\n// Questions with a `family` share their options with a practice twin in bank.js that keys a different option.\nwindow.BANK = window.BANK || [];\nwindow.BANK.push(\n";
fs.writeFileSync(path.join(ROOT, "app/content/holdout.js"), head + holdout.map(item).join(",\n") + "\n);\n");

// Practice twins: one marked block at the end of bank.js.
const MARK = "  // ---- Option-family practice twins (generated by scripts/audit/build-families.mjs) ----";
const p = path.join(ROOT, "app/content/bank.js");
let src = fs.readFileSync(p, "utf8");
const cut = src.indexOf(MARK);
if (cut >= 0) src = src.slice(0, cut).replace(/,\s*$/, "\n") + "];\n";
const end = src.lastIndexOf("];");
const twins = fams.map(f => member(f, f.p, false));
src = src.slice(0, end).replace(/\s*$/, "") + ",\n" + MARK + "\n" + twins.map(item).join(",\n") + "\n" + src.slice(end);
fs.writeFileSync(p, src);
console.log(`Families: ${fams.length} · holdout replaced: ${Object.keys(byId).length} · practice twins: ${twins.length}`);
